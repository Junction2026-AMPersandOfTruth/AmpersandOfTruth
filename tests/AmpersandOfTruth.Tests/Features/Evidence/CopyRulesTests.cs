        Assert.Contains(violations, v => string.Equals(v.Rule.Term, term, StringComparison.OrdinalIgnoreCase));
    }

    [Theory]
    [InlineData("provenance")]
    [InlineData("frontier")]
    [InlineData("controller")]
    [InlineData("deliberation")]
    [InlineData("unintentional")]
    [InlineData("sha256")]
    public void Near_misses_do_not_trigger_any_rule(string text)
    {
        var violations = CopyRules.FindViolations(text, includeJargon: true);
        Assert.Empty(violations);
    }

    [Fact]
    public void IncludeJargon_false_skips_jargon_only()
    {
        var text = "These trolls tried to push proven falsehoods in this tier, but were Reverted by LLMs with sha1 check.";

        var withJargon = CopyRules.FindViolations(text, includeJargon: true);
        var withoutJargon = CopyRules.FindViolations(text, includeJargon: false);

        Assert.Contains(withJargon, v => v.Rule.Kind == CopyRuleKind.Jargon);
        Assert.DoesNotContain(withoutJargon, v => v.Rule.Kind == CopyRuleKind.Jargon);

        var jargonCount = withJargon.Count(v => v.Rule.Kind == CopyRuleKind.Jargon);
        Assert.True(jargonCount >= 4); // tier, Reverted, LLMs, sha1
        Assert.Equal(withJargon.Count - jargonCount, withoutJargon.Count);

        // Non-jargon violations must match exactly
        Assert.Equal(
            withJargon.Where(v => v.Rule.Kind != CopyRuleKind.Jargon).Select(v => v.Rule.Term),
            withoutJargon.Select(v => v.Rule.Term));
    }

    [Fact]
    public void FindViolations_orders_by_index_and_records_matched_text()
    {
        var text = "First tier, then trolls, finally Reverted.";

        var violations = CopyRules.FindViolations(text, includeJargon: true);

        Assert.Equal(3, violations.Count);

        Assert.Equal("tier", violations[0].Match);
        Assert.Equal("tier", violations[0].Rule.Term);
        Assert.Equal(text.IndexOf("tier", StringComparison.Ordinal), violations[0].Index);

        Assert.Equal("trolls", violations[1].Match);
        Assert.Equal("troll", violations[1].Rule.Term);
        Assert.Equal(text.IndexOf("trolls", StringComparison.Ordinal), violations[1].Index);

        Assert.Equal("Reverted", violations[2].Match);
        Assert.Equal("revert", violations[2].Rule.Term);
        Assert.Equal(text.IndexOf("Reverted", StringComparison.Ordinal), violations[2].Index);

        for (var i = 0; i < violations.Count; i++)
        {
            var v = violations[i];
            Assert.Equal(v.Match, text.Substring(v.Index, v.Match.Length));
            if (i > 0)
            {
                Assert.True(violations[i].Index >= violations[i - 1].Index);
            }
        }
    }

    [Fact]
    public void FindViolations_handles_empty_or_null_text()
    {
        Assert.Empty(CopyRules.FindViolations(""));
        Assert.Empty(CopyRules.FindViolations(null!));
    }

    [Fact]
    public void FindViolations_detects_multiple_occurrences_of_same_term()
    {
        var text = "One troll met another troll.";
        var violations = CopyRules.FindViolations(text, includeJargon: false);

        Assert.Equal(2, violations.Count);
        Assert.All(violations, v => Assert.Equal("troll", v.Rule.Term));
        Assert.Equal(4, violations[0].Index);
        Assert.Equal(22, violations[1].Index);
    }
