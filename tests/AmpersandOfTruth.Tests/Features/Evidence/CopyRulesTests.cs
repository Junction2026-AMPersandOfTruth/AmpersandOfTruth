namespace AmpersandOfTruth.Tests.Features.Evidence;

using AmpersandOfTruth.Web.Features.Evidence;
using Xunit;

public sealed class CopyRulesTests
{
    [Fact]
    public void All_rules_have_expected_count_and_unique_terms()
    {
        Assert.Equal(21, CopyRules.All.Count);

        var terms = CopyRules.All.Select(r => r.Term).ToList();
        Assert.Equal(terms.Distinct(StringComparer.OrdinalIgnoreCase).Count(), terms.Count);

        foreach (var rule in CopyRules.All)
        {
            Assert.False(string.IsNullOrWhiteSpace(rule.Term));
            Assert.False(string.IsNullOrWhiteSpace(rule.Advice));
            Assert.NotNull(rule.Pattern);
        }
    }

