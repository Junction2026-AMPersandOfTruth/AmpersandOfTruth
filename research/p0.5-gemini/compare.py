#!/usr/bin/env python3
"""P0.5 (#16) Finnish quality check: compare classify-edit outputs across Gemini models.

    python3 research/p0.5-gemini/compare.py \
        --sample research/p0.5-gemini/sample20.jsonl \
        --results research/p0.5-gemini/results/classify-edit-v1.jsonl \
        [--judge research/p0.5-gemini/judge-claude.json] \
        --out research/p0.5-gemini/REPORT.md --review-csv research/p0.5-gemini/human-review.csv

Inputs: the sample (extract_sample.py) and the JSONL written by `scripts/analyze.sh batch` (one line per id × model).
Stdlib only. Objective checks need no labels: schema-valid rate, verbatim-evidence rate (are quoted spans really in
the input? — the cheapest Finnish-quality / hallucination signal), claim_en/claim_fi consistency, latency, tokens, cost,
and agreement between models. The optional judge file adds a blind, different-vendor rating per output.
"""
import argparse
import collections
import csv
import json
import re
import statistics
from pathlib import Path

MODEL_ORDER = ["gemini-4-hydrogen", "gemini-4-carbon", "gemini-4-argon", "gemini-3.8-flash", "gemini-3.5-flash-lite"]
CATS = ["vandalism", "test_or_nonsense", "good_faith_error", "content_dispute", "pov_push",
        "false_factual_claim", "source_manipulation", "other"]
SHORT = {"vandalism": "vand", "test_or_nonsense": "test", "good_faith_error": "gf-err", "content_dispute": "dispute",
         "pov_push": "POV", "false_factual_claim": "FALSE", "source_manipulation": "src", "other": "other"}
# Coarse buckets: what the product actually cares about is "noise" vs "narrative-relevant".
COARSE = {"vandalism": "noise", "test_or_nonsense": "noise", "good_faith_error": "benign", "content_dispute": "benign",
          "other": "benign", "pov_push": "narrative", "false_factual_claim": "narrative", "source_manipulation": "narrative"}


def load_jsonl(path):
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def norm(s):
    return re.sub(r"\s+", " ", s or "").strip().casefold()


def pct(n, d):
    return f"{100 * n / d:.0f}%" if d else "—"


def p95(xs):
    if not xs:
        return 0
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(round(0.95 * (len(xs) - 1))))]


def kappa(a, b):
    """Cohen's kappa over paired labels (None pairs dropped)."""
    pairs = [(x, y) for x, y in zip(a, b) if x and y]
    if not pairs:
        return None
    n = len(pairs)
    po = sum(x == y for x, y in pairs) / n
    ca, cb = collections.Counter(x for x, _ in pairs), collections.Counter(y for _, y in pairs)
    pe = sum(ca[k] * cb[k] for k in set(ca) | set(cb)) / (n * n)
    return 1.0 if pe == 1 else (po - pe) / (1 - pe)


def trunc(s, n):
    s = (s or "").replace("\n", " ").replace("|", "\\|")
    return s if len(s) <= n else s[: n - 1] + "…"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sample", required=True)
    ap.add_argument("--results", required=True)
    ap.add_argument("--judge")
    ap.add_argument("--out", required=True)
    ap.add_argument("--review-csv")
    a = ap.parse_args()

    sample = {r["_id"]: r for r in load_jsonl(a.sample)}
    results = load_jsonl(a.results)
    by = collections.defaultdict(dict)  # id -> model -> line
    for r in results:
        by[r["id"]][r["model"]] = r
    models = [m for m in MODEL_ORDER if any(m in v for v in by.values())]
    models += sorted({r["model"] for r in results} - set(models))
    ids = [i for i in sample if i in by]
    judge = json.load(open(a.judge, encoding="utf-8")) if a.judge else None

    out = []
    w = out.append
    w("# P0.5 · Finnish quality check — classify-edit v1 across Gemini models\n")
    w(f"{len(ids)} real reverted Finnish Wikipedia edits × {len(models)} models. Generated by `research/p0.5-gemini/compare.py`; "
      "inputs `sample20.jsonl` (from `extract_sample.py`) and `results/` (from `scripts/analyze.sh batch`).\n")
    w("**Not yet a human verdict.** Objective checks below need no labels; the judge column (if present) is a blind rating by a "
      "different vendor's model (Claude) — a human still needs to read `human-review.csv` (issue #16 Done-when).\n")

    # ── per-model stats ──────────────────────────────────────────────────────────
    w("## Per model\n")
    w("| Model | OK | invalid / blocked / failed | median / p95 latency | in / out / thought tok per edit | $ per edit | $ per 1k edits | evidence verbatim | claim fi/en consistent |")
    w("|---|---|---|---|---|---|---|---|---|")
    stats = {}
    for m in models:
        rows = [by[i][m] for i in ids if m in by[i]]
        live = [r for r in rows if not r.get("from_cache")]
        ok = [r for r in rows if r["outcome"] == "ok"]
        lat = [r["latency_ms"] for r in live] or [r["latency_ms"] for r in rows]
        n = len(rows)
        spans = verbatim = 0
        consistent = 0
        for r in ok:
            s = sample[r["id"]]
            hay = "\n".join(s.get(k) or "" for k in ("inserted_text", "removed_text", "edit_summary", "revert_summary", "context"))
            hay_n = norm(hay)
            for e in r["value"].get("evidence") or []:
                spans += 1
                verbatim += 1 if (e in hay or norm(e) in hay_n) else 0
            consistent += (r["value"].get("claim_en") is None) == (r["value"].get("claim_fi") is None)
        cost = sum(r.get("cost_usd", 0) for r in rows)
        tin = statistics.mean(r["input_tokens"] for r in rows) if rows else 0
        tout = statistics.mean(r["output_tokens"] for r in rows) if rows else 0
        tth = statistics.mean(r["thought_tokens"] for r in rows) if rows else 0
        bad = collections.Counter(r["outcome"] for r in rows)
        stats[m] = dict(n=n, ok=len(ok), verbatim=(verbatim, spans))
        w(f"| `{m}` | {len(ok)}/{n} | {bad['invalid']} / {bad['blocked']} / {bad['failed'] + bad['truncated']} | "
          f"{statistics.median(lat):.0f} / {p95(lat):.0f} ms | {tin:.0f} / {tout:.0f} / {tth:.0f} | "
          f"${cost / n if n else 0:.5f} | ${1000 * cost / n if n else 0:.2f} | {pct(verbatim, spans)} ({verbatim}/{spans}) | {pct(consistent, len(ok))} |")
    w("\nLatency is per call as seen by the client (incl. retries); cached rows are excluded from latency when live rows exist. "
      "Cost uses `Gemini:Pricing` (Carbon/Argon prices double on 2026-12-01). \"Evidence verbatim\" = share of quoted spans found in "
      "the input exactly or after whitespace/case normalisation — a quote that is not in the input is a hallucination or a silent translation.\n")

    # ── agreement ────────────────────────────────────────────────────────────────
    w("## Agreement between models (Cohen's κ on category · on coarse noise/benign/narrative)\n")
    def cat_of(i, m):
        r = by[i].get(m)
        return r["value"].get("category") if r and r["outcome"] == "ok" else None

    labels = {m: [cat_of(i, m) for i in ids] for m in models}
    w("| | " + " | ".join(f"`{m}`" for m in models) + " |")
    w("|---|" + "---|" * len(models))
    for m1 in models:
        cells = []
        for m2 in models:
            if m1 == m2:
                cells.append("—")
                continue
            k1 = kappa(labels[m1], labels[m2])
            k2 = kappa([COARSE.get(x) if x else None for x in labels[m1]], [COARSE.get(x) if x else None for x in labels[m2]])
            cells.append(f"{k1:.2f} · {k2:.2f}" if k1 is not None else "—")
        w(f"| `{m1}` | " + " | ".join(cells) + " |")
    w("")

    # ── category distribution ───────────────────────────────────────────────────
    w("## Category distribution\n")
    w("| Model | " + " | ".join(SHORT[c] for c in CATS) + " | mean confidence |")
    w("|---|" + "---|" * (len(CATS) + 1))
    for m in models:
        c = collections.Counter(x for x in labels[m] if x)
        confs = [by[i][m]["value"]["confidence"] for i in ids if by[i].get(m, {}).get("outcome") == "ok"]
        w(f"| `{m}` | " + " | ".join(str(c[k]) for k in CATS) + f" | {statistics.mean(confs) if confs else 0:.1f} |")
    w("")

    # ── judge ─────────────────────────────────────────────────────────────────────
    if judge:
        w("## Blind judge (Claude, different vendor)\n")
        w("Per output: category acceptable? (yes / partly / no), claim faithful to the Finnish (1–5), English quality (1–5), hallucinated content? The judge saw models as anonymous letters.\n")
        w("| Model | category yes / partly / no | claim faithful (mean) | English (mean) | hallucination | judge agrees with model's coarse bucket |")
        w("|---|---|---|---|---|---|")
        for m in models:
            js = [j for j in judge.get("ratings", []) if j.get("model") == m]
            cat = collections.Counter(j.get("category_ok") for j in js)
            faith = [j["claim_faithful"] for j in js if isinstance(j.get("claim_faithful"), (int, float))]
            eng = [j["english_quality"] for j in js if isinstance(j.get("english_quality"), (int, float))]
            hall = sum(1 for j in js if j.get("hallucination"))
            coarse_ok = 0
            for j in js:
                ref = (judge.get("reference", {}).get(j["id"]) or {}).get("category")
                got = cat_of(j["id"], m)
                coarse_ok += 1 if ref and got and COARSE.get(ref) == COARSE.get(got) else 0
            w(f"| `{m}` | {cat['yes']} / {cat['partly']} / {cat['no']} | {statistics.mean(faith) if faith else 0:.2f} | "
              f"{statistics.mean(eng) if eng else 0:.2f} | {hall} | {pct(coarse_ok, len(js))} |")
        w("")

    # ── per edit ─────────────────────────────────────────────────────────────────
    w("## Per edit\n")
    w("| # | Article · bucket | Inserted (start) | " + " | ".join(f"`{m.replace('gemini-', '')}`" for m in models) +
      (" | judge ref |" if judge else " |"))
    w("|---|---|---|" + "---|" * len(models) + ("---|" if judge else ""))
    for n, i in enumerate(ids, 1):
        s = sample[i]
        cells = []
        for m in models:
            r = by[i].get(m)
            if not r:
                cells.append("")
            elif r["outcome"] != "ok":
                cells.append(f"**{r['outcome']}**")
            else:
                cells.append(f"{SHORT[r['value']['category']]} ({r['value']['confidence']})")
        ref = (judge.get("reference", {}).get(i) or {}).get("category") if judge else None
        w(f"| [{n}]({s['diff_url']}) | {trunc(s['article_title'], 40)} · {s.get('selection_bucket', '')} | {trunc(s['inserted_text'], 70)} | "
          + " | ".join(cells) + (f" | {SHORT.get(ref, '')} |" if judge else " |"))
    w("")

    w("## Extracted claims, side by side (Hydrogen vs Carbon)\n")
    for n, i in enumerate(ids, 1):
        s = sample[i]
        w(f"**{n}. {s['article_title']}** — [diff]({s['diff_url']})  ")
        for m in ("gemini-4-hydrogen", "gemini-4-carbon"):
            r = by[i].get(m)
            if r and r["outcome"] == "ok":
                v = r["value"]
                w(f"- `{m}` **{v['category']}** ({v['confidence']}): {v.get('claim_en') or '_no claim_'} — _{trunc(v['what_changed_en'], 220)}_  ")
            elif r:
                w(f"- `{m}` **{r['outcome']}**: {trunc(r.get('error'), 160)}  ")
        w("")

    Path(a.out).write_text("\n".join(out) + "\n", encoding="utf-8")

    if a.review_csv:
        with open(a.review_csv, "w", newline="", encoding="utf-8") as f:
            cw = csv.writer(f)
            hdr = ["n", "id", "article", "diff_url", "inserted_text", "removed_text"]
            for m in models:
                hdr += [f"{m}:category", f"{m}:claim_en", f"{m}:what_changed_en"]
            hdr += ["human_category", "best_model", "worst_model", "hydrogen_ok(y/n)", "carbon_ok(y/n)", "notes"]
            cw.writerow(hdr)
            for n, i in enumerate(ids, 1):
                s = sample[i]
                row = [n, i, s["article_title"], s["diff_url"], s["inserted_text"][:500], s["removed_text"][:500]]
                for m in models:
                    r = by[i].get(m)
                    v = r["value"] if r and r["outcome"] == "ok" else {}
                    row += [v.get("category") or (r or {}).get("outcome", ""), v.get("claim_en") or "", v.get("what_changed_en") or ""]
                row += ["", "", "", "", "", ""]
                cw.writerow(row)
    print(f"wrote {a.out}" + (f" and {a.review_csv}" if a.review_csv else ""))


if __name__ == "__main__":
    main()
